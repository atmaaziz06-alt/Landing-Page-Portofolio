CREATE OR REPLACE FUNCTION public.cms_initialize(p_seed jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_table text;
  v_sequence text;
  v_max_id bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('portfolio-cms-seed', 0));
  IF EXISTS (SELECT 1 FROM public.activity_logs) THEN
    RETURN;
  END IF;

  FOREACH v_table IN ARRAY ARRAY[
    'users', 'profiles', 'projects', 'experiences', 'tools', 'skills',
    'social_links', 'contact_settings', 'site_settings', 'events', 'certifications'
  ]
  LOOP
    IF jsonb_typeof(p_seed -> v_table) = 'array'
      AND jsonb_array_length(p_seed -> v_table) > 0 THEN
      EXECUTE format(
        'INSERT INTO public.%I SELECT (jsonb_populate_recordset(NULL::public.%I, $1)).* ON CONFLICT DO NOTHING',
        v_table, v_table
      ) USING p_seed -> v_table;
    END IF;
  END LOOP;

  FOREACH v_table IN ARRAY ARRAY[
    'users', 'experiences', 'tools', 'skills', 'social_links', 'events', 'certifications'
  ]
  LOOP
    v_sequence := pg_get_serial_sequence(format('public.%I', v_table), 'id');
    IF v_sequence IS NOT NULL THEN
      EXECUTE format('SELECT max(id)::bigint FROM public.%I', v_table) INTO v_max_id;
      PERFORM setval(v_sequence::regclass, GREATEST(COALESCE(v_max_id, 1), 1), v_max_id IS NOT NULL);
    END IF;
  END LOOP;

  INSERT INTO public.activity_logs (action, details)
  VALUES ('Database Initialized', 'Seeded initial CMS content.');
END;
$$;

-- One narrowly scoped server RPC gives the existing parameterized SQL layer a
-- PostgreSQL backend. Values are quoted as literals inside the database, and
-- only the server's service-role key is allowed to invoke this function.
CREATE OR REPLACE FUNCTION public.cms_execute(
  p_sql text,
  p_params jsonb DEFAULT '[]'::jsonb,
  p_mode text DEFAULT 'all'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_sql text := p_sql;
  v_param jsonb;
  v_position integer;
  v_literal text;
  v_rows jsonb;
  v_changed integer;
  v_id text;
BEGIN
  IF p_sql IS NULL OR p_mode NOT IN ('one', 'all', 'run') THEN
    RAISE EXCEPTION 'Invalid CMS query request';
  END IF;

  FOR v_param IN SELECT value FROM jsonb_array_elements(COALESCE(p_params, '[]'::jsonb))
  LOOP
    v_position := strpos(v_sql, '?');
    IF v_position = 0 THEN
      RAISE EXCEPTION 'CMS query parameter count mismatch';
    END IF;
    IF v_param = 'null'::jsonb THEN
      v_literal := 'NULL';
    ELSE
      v_literal := quote_literal(v_param #>> '{}');
    END IF;
    v_sql := overlay(v_sql placing v_literal from v_position for 1);
  END LOOP;

  IF strpos(v_sql, '?') > 0 THEN
    RAISE EXCEPTION 'CMS query parameter count mismatch';
  END IF;

  IF p_mode IN ('one', 'all') THEN
    EXECUTE format(
      'SELECT COALESCE(jsonb_agg(to_jsonb(_cms_row)), ''[]''::jsonb) FROM (%s) AS _cms_row',
      v_sql
    ) INTO v_rows;
    IF p_mode = 'one' THEN
      RETURN COALESCE(v_rows -> 0, 'null'::jsonb);
    END IF;
    RETURN COALESCE(v_rows, '[]'::jsonb);
  END IF;

  IF v_sql ~* '^\s*INSERT\s' THEN
    IF v_sql !~* '\sRETURNING\s' THEN
      v_sql := v_sql || ' RETURNING *';
    END IF;
    EXECUTE
      'WITH _cms_changed AS (' || v_sql || ') ' ||
      'SELECT COALESCE(jsonb_agg(to_jsonb(_cms_changed)), ''[]''::jsonb) FROM _cms_changed'
      INTO v_rows;
    v_changed := jsonb_array_length(COALESCE(v_rows, '[]'::jsonb));
    v_id := v_rows -> 0 ->> 'id';
    RETURN jsonb_build_object(
      'changes', v_changed,
      'lastInsertRowid', CASE WHEN v_id ~ '^-?[0-9]+$' THEN to_jsonb(v_id::bigint) ELSE to_jsonb(v_id) END
    );
  ELSIF v_sql ~* '^\s*(UPDATE|DELETE)\s' THEN
    IF v_sql !~* '\sRETURNING\s' THEN
      v_sql := v_sql || ' RETURNING *';
    END IF;
    EXECUTE
      'WITH _cms_changed AS (' || v_sql || ') ' ||
      'SELECT COALESCE(jsonb_agg(to_jsonb(_cms_changed)), ''[]''::jsonb) FROM _cms_changed'
      INTO v_rows;
    v_changed := jsonb_array_length(COALESCE(v_rows, '[]'::jsonb));
    RETURN jsonb_build_object('changes', v_changed);
  END IF;

  RAISE EXCEPTION 'Unsupported CMS statement';
END;
$$;

CREATE OR REPLACE FUNCTION public.cms_save_content_snapshot(
  p_section text,
  p_section_key text,
  p_action text,
  p_details text,
  p_snapshot jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_timestamp timestamptz;
  v_previous_snapshot text;
  v_stamped_snapshot text;
  v_entry public.content_history%ROWTYPE;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('portfolio-cms-history', 0));
  v_timestamp := clock_timestamp();
  SELECT snapshot_json INTO v_previous_snapshot
  FROM public.content_history
  ORDER BY id DESC
  LIMIT 1;

  v_stamped_snapshot := (p_snapshot || jsonb_build_object('updatedAt', v_timestamp))::text;
  INSERT INTO public.content_history (
    timestamp, section, section_key, action, details, snapshot_json, previous_snapshot_json
  ) VALUES (
    v_timestamp, COALESCE(p_section, 'Konten'), COALESCE(p_section_key, ''),
    COALESCE(p_action, 'Update'), COALESCE(p_details, ''),
    v_stamped_snapshot, v_previous_snapshot
  ) RETURNING * INTO v_entry;

  DELETE FROM public.content_history
  WHERE id NOT IN (
    SELECT id FROM public.content_history ORDER BY id DESC LIMIT 40
  );

  RETURN to_jsonb(v_entry);
END;
$$;

CREATE OR REPLACE FUNCTION public.cms_restore_content_snapshot(p_history_id bigint)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_selected public.content_history%ROWTYPE;
  v_snapshot jsonb;
  v_item jsonb;
  v_timestamp timestamptz;
  v_previous_snapshot text;
  v_stamped_snapshot text;
  v_entry public.content_history%ROWTYPE;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('portfolio-cms-history', 0));
  SELECT * INTO v_selected FROM public.content_history WHERE id = p_history_id;
  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  v_timestamp := clock_timestamp();
  v_snapshot := v_selected.snapshot_json::jsonb;

  UPDATE public.profiles SET
    name = COALESCE(v_snapshot #>> '{profile,name}', ''),
    brand_name = COALESCE(v_snapshot #>> '{profile,brandName}', ''),
    monogram = COALESCE(v_snapshot #>> '{profile,monogram}', ''),
    eyebrow = COALESCE(v_snapshot #>> '{profile,eyebrow}', ''),
    role = COALESCE(v_snapshot #>> '{profile,role}', ''),
    location = COALESCE(v_snapshot #>> '{profile,location}', ''),
    headline_prefix = COALESCE(v_snapshot #>> '{profile,headlinePrefix}', ''),
    description = COALESCE(v_snapshot #>> '{profile,description}', ''),
    bio = COALESCE(v_snapshot #>> '{profile,bio}', ''),
    avatar_url = COALESCE(v_snapshot #>> '{profile,avatarUrl}', ''),
    about_image_url = COALESCE(v_snapshot #>> '{profile,aboutImageUrl}', ''),
