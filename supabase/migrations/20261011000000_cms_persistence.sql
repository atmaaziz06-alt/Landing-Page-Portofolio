    resume_label = COALESCE(v_snapshot #>> '{profile,availability,resumeLabel}', ''),
    updated_at = v_timestamp
  WHERE id = 1;

  DELETE FROM public.projects;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'projects')
  LOOP
    INSERT INTO public.projects (
      id, title, category, type, year, image, images, description, role, client,
      link, link_label, services, highlight, deliverables, display_order, is_visible
    ) VALUES (
      v_item ->> 'id', COALESCE(v_item ->> 'title', ''), COALESCE(v_item ->> 'category', ''),
      COALESCE(v_item ->> 'type', ''), COALESCE(v_item ->> 'year', ''),
      COALESCE(v_item ->> 'image', ''),
      CASE WHEN jsonb_typeof(v_item -> 'images') = 'array' THEN (v_item -> 'images')::text
           ELSE COALESCE(v_item ->> 'images', '[]') END,
      COALESCE(v_item ->> 'description', ''), COALESCE(v_item ->> 'role', ''),
      COALESCE(v_item ->> 'client', ''), COALESCE(v_item ->> 'link', ''),
      COALESCE(v_item ->> 'linkLabel', ''),
      CASE WHEN jsonb_typeof(v_item -> 'services') = 'array' THEN (v_item -> 'services')::text
           ELSE COALESCE(v_item ->> 'services', '[]') END,
      COALESCE(v_item ->> 'highlight', ''),
      CASE WHEN jsonb_typeof(v_item -> 'deliverables') = 'array' THEN (v_item -> 'deliverables')::text
           ELSE COALESCE(v_item ->> 'deliverables', '') END,
      COALESCE((v_item ->> 'displayOrder')::integer, 0),
      CASE WHEN v_item -> 'isVisible' = 'false'::jsonb THEN 0 ELSE 1 END
    );
  END LOOP;

  DELETE FROM public.experiences;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'experience')
  LOOP
    INSERT INTO public.experiences (
      id, period, role, company, location, description, highlights, logo_url, display_order, is_visible
    ) VALUES (
      (v_item ->> 'id')::bigint, COALESCE(v_item ->> 'period', ''), COALESCE(v_item ->> 'role', ''),
      COALESCE(v_item ->> 'company', ''), COALESCE(v_item ->> 'location', ''),
      COALESCE(v_item ->> 'description', ''),
      CASE WHEN jsonb_typeof(v_item -> 'highlights') = 'array' THEN (v_item -> 'highlights')::text
           ELSE COALESCE(v_item ->> 'highlights', '[]') END,
      COALESCE(v_item ->> 'logoUrl', ''), COALESCE((v_item ->> 'displayOrder')::integer, 0),
      CASE WHEN v_item -> 'isVisible' = 'false'::jsonb THEN 0 ELSE 1 END
    );
  END LOOP;

  DELETE FROM public.tools;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'tools')
  LOOP
    INSERT INTO public.tools (
      id, name, role, category, icon_key, custom_icon_url, display_order, is_visible
    ) VALUES (
      (v_item ->> 'id')::bigint, COALESCE(v_item ->> 'name', ''), COALESCE(v_item ->> 'role', ''),
      COALESCE(v_item ->> 'category', ''), COALESCE(v_item ->> 'iconKey', ''),
      COALESCE(v_item ->> 'customIconUrl', ''), COALESCE((v_item ->> 'displayOrder')::integer, 0),
      CASE WHEN v_item -> 'isVisible' = 'false'::jsonb THEN 0 ELSE 1 END
    );
  END LOOP;

  DELETE FROM public.skills;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'skills')
  LOOP
    INSERT INTO public.skills (
      id, number, title, description, deliverables, display_order, is_visible
    ) VALUES (
      (v_item ->> 'id')::bigint, COALESCE(v_item ->> 'number', ''),
      COALESCE(v_item ->> 'title', ''), COALESCE(v_item ->> 'description', ''),
      CASE WHEN jsonb_typeof(v_item -> 'deliverables') = 'array' THEN (v_item -> 'deliverables')::text
           ELSE COALESCE(v_item ->> 'deliverables', '[]') END,
      COALESCE((v_item ->> 'displayOrder')::integer, 0),
      CASE WHEN v_item -> 'isVisible' = 'false'::jsonb THEN 0 ELSE 1 END
    );
  END LOOP;

  DELETE FROM public.events;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'events')
  LOOP
    INSERT INTO public.events (
      id, title, organizer, date, period, location, role, description, image_url,
      link_url, display_order, is_visible
    ) VALUES (
      (v_item ->> 'id')::bigint, COALESCE(v_item ->> 'title', ''),
      COALESCE(v_item ->> 'organizer', ''), COALESCE(v_item ->> 'date', ''),
      COALESCE(v_item ->> 'period', ''), COALESCE(v_item ->> 'location', ''),
      COALESCE(v_item ->> 'role', ''), COALESCE(v_item ->> 'description', ''),
      COALESCE(v_item ->> 'imageUrl', ''), COALESCE(v_item ->> 'linkUrl', ''),
      COALESCE((v_item ->> 'displayOrder')::integer, 0),
      CASE WHEN v_item -> 'isVisible' = 'false'::jsonb THEN 0 ELSE 1 END
    );
  END LOOP;

  DELETE FROM public.certifications;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'certifications')
  LOOP
    INSERT INTO public.certifications (
      id, title, issuer, issue_date, expiry_date, credential_id, credential_url,
      image_url, category, description, display_order, is_visible
    ) VALUES (
      (v_item ->> 'id')::bigint, COALESCE(v_item ->> 'title', ''),
      COALESCE(v_item ->> 'issuer', ''), COALESCE(v_item ->> 'issueDate', ''),
      COALESCE(v_item ->> 'expiryDate', ''), COALESCE(v_item ->> 'credentialId', ''),
      COALESCE(v_item ->> 'credentialUrl', ''), COALESCE(v_item ->> 'imageUrl', ''),
      COALESCE(v_item ->> 'category', ''), COALESCE(v_item ->> 'description', ''),
      COALESCE((v_item ->> 'displayOrder')::integer, 0),
      CASE WHEN v_item -> 'isVisible' = 'false'::jsonb THEN 0 ELSE 1 END
    );
  END LOOP;

  DELETE FROM public.social_links;
  FOR v_item IN SELECT value FROM jsonb_array_elements(v_snapshot -> 'socials')
  LOOP
    INSERT INTO public.social_links (id, name, url, username, display_order, is_visible)
    VALUES (
      (v_item ->> 'id')::bigint, COALESCE(v_item ->> 'name', ''),
      COALESCE(v_item ->> 'url', ''), COALESCE(v_item ->> 'username', ''),
      COALESCE((v_item ->> 'displayOrder')::integer, 0),
