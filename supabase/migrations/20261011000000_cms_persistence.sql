  WHERE id = 1;

  UPDATE public.site_settings SET
    site_title = COALESCE(v_snapshot #>> '{settings,siteTitle}', ''),
    brand_name = COALESCE(v_snapshot #>> '{settings,brandName}', ''),
    site_description = COALESCE(v_snapshot #>> '{settings,siteDescription}', ''),
