    updated_at = v_timestamp
  WHERE id = 1;

  PERFORM setval(pg_get_serial_sequence('public.experiences', 'id'),
    GREATEST(COALESCE((SELECT max(id) FROM public.experiences), 1), 1),
    EXISTS (SELECT 1 FROM public.experiences));
  PERFORM setval(pg_get_serial_sequence('public.tools', 'id'),
    GREATEST(COALESCE((SELECT max(id) FROM public.tools), 1), 1),
    EXISTS (SELECT 1 FROM public.tools));
  PERFORM setval(pg_get_serial_sequence('public.skills', 'id'),
    GREATEST(COALESCE((SELECT max(id) FROM public.skills), 1), 1),
    EXISTS (SELECT 1 FROM public.skills));
  PERFORM setval(pg_get_serial_sequence('public.events', 'id'),
    GREATEST(COALESCE((SELECT max(id) FROM public.events), 1), 1),
    EXISTS (SELECT 1 FROM public.events));
  PERFORM setval(pg_get_serial_sequence('public.certifications', 'id'),
    GREATEST(COALESCE((SELECT max(id) FROM public.certifications), 1), 1),
    EXISTS (SELECT 1 FROM public.certifications));
  PERFORM setval(pg_get_serial_sequence('public.social_links', 'id'),
    GREATEST(COALESCE((SELECT max(id) FROM public.social_links), 1), 1),
    EXISTS (SELECT 1 FROM public.social_links));

  SELECT snapshot_json INTO v_previous_snapshot
  FROM public.content_history ORDER BY id DESC LIMIT 1;
  v_stamped_snapshot := (v_snapshot || jsonb_build_object('updatedAt', v_timestamp))::text;
  INSERT INTO public.content_history (
    timestamp, section, section_key, action, details, snapshot_json, previous_snapshot_json
  ) VALUES (
